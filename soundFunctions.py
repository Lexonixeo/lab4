"""Аналитическая модель скорости звука во влажном воздухе с примесью CO2.

Все числа взяты из таблиц пособия (т4.2, т4.3):
  * газовая постоянная и атмосферное давление;
  * давление насыщенных паров воды при температурах от 20 до 30 °C;
  * молярные массы и числа степеней свободы молекул;
  * доли газов в сухом воздухе.

Пункт 4.5 лабораторной работы.
"""
import numpy as np

# Газовая постоянная, Дж/(моль·К)
R = 8.314

# Атмосферное давление, Па
PA = 101325

# Давление насыщенных паров воды, Па, при температурах, °C (таблица из т4.3)
TEMPS = [20, 22, 24, 26, 28, 30]
PW0 = [2336.8, 2642.4, 2982.4, 3360.0, 3778.5, 4241.7]

# Молярные массы, кг/моль, и числа степеней свободы молекул (таблица из т4.2)
M_N2, M_O2, M_AR, M_CO2, M_H2O = 0.02801, 0.03200, 0.03995, 0.04401, 0.01802
I_N2, I_O2, I_AR, I_CO2, I_H2O = 5, 5, 3, 6, 6

# Доли газов в сухом воздухе (т4.3). X_O2 — сумма долей кислорода и CO2: 0,2095 + 0,0003
X_N2, X_O2, X_AR = 0.7809, 0.2098, 0.0093


def h2oFraction(temperature, rh):
    """Мольная доля паров воды по температуре (°C) и относительной влажности (%)."""
    pw0 = np.interp(temperature, TEMPS, PW0)   # давление насыщенных паров, Па
    h2oX = rh / 100 * pw0 / PA                 # мольная доля паров воды
    return h2oX


def speedOfSound(temperature, h2oX, co2Max):
    """Скорость звука во влажном воздухе с примесью CO2.

    temperature — температура, °C;
    h2oX        — мольная доля паров воды;
    co2Max      — наибольшая доля CO2 в сухом воздухе, %.

    Возвращает массив долей CO2 (%) и массив скоростей звука (м/с) для
    51 значения доли CO2 от 0 до co2Max.
    """
    T = temperature + 273.15
    co2 = np.linspace(0, co2Max / 100, 51)   # доля CO2 в сухом воздухе

    # CO2 замещает кислород, пары воды разбавляют остальные газы в (1 - h2oX) раз
    k = 1 - h2oX
    xN2 = X_N2 * k
    xO2 = (X_O2 - co2) * k
    xAr = X_AR * k
    xCO2 = co2 * k

    # Молярная масса смеси
    M = M_N2 * xN2 + M_O2 * xO2 + M_AR * xAr + M_CO2 * xCO2 + M_H2O * h2oX

    # Теплоёмкости смеси: C_v компонента = i/2 * R
    Cv = (I_N2 * xN2 + I_O2 * xO2 + I_AR * xAr + I_CO2 * xCO2 + I_H2O * h2oX) / 2 * R
    Cp = Cv + R

    soundSpeed = np.sqrt(Cp / Cv * R * T / M)
    return co2 * 100, soundSpeed


if __name__ == "__main__":
    # Самопроверка по пунктам «Как проверить» из п4.5
    print("Сухой воздух, 20 °C:      %.2f м/с (ожидается ~343,4)"
          % speedOfSound(20, 0, 5)[1][0])
    print("21,9 °C, 34 %%, без CO2:  %.2f м/с (ожидается ~345,0)"
          % speedOfSound(21.9, h2oFraction(21.9, 34), 5)[1][0])
    co2, c = speedOfSound(21.9, h2oFraction(21.9, 34), 5)
    cw = speedOfSound(21.9, h2oFraction(21.9, 100), 5)[1]
    print("Наклон: %.2f м/с на 1 %% CO2 (ожидается ~-0,8)"
          % (c[10] - c[0]))
    print("Разница влажностей 34 -> 100 %%: %.2f м/с (ожидается ~1,0)"
          % (cw[0] - c[0]))
    print("h2oFraction(21.9, 34) = %.4f (ожидается ~0,0088)" % h2oFraction(21.9, 34))
    print("h2oFraction(21.9, 100) = %.4f (ожидается ~0,026)" % h2oFraction(21.9, 100))
